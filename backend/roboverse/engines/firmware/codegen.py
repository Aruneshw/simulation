"""Firmware generation and build integration.

Generates a PlatformIO project that implements the *same* controller as the
behavioural model used in simulation (diff-drive kinematics + per-wheel PI on
encoder speed), with pins taken from the project's firmware pin map. It also
speaks the HIL serial protocol so the physical board can be put in the loop.
"""
from __future__ import annotations

import re
import shutil
import subprocess
import tempfile
from pathlib import Path

from ...schemas.project import Project
from .targets import TARGETS

HIL_PROTOCOL = """RoboVerse HIL serial protocol (115200 8N1, newline-terminated ASCII)
host -> board : C <v_mps> <w_radps>      velocity command
host -> board : E <0|1>                  emergency stop (1 = stop, motors coast/brake)
board -> host : T <ms> <enc_left> <enc_right> <duty_left> <duty_right>   telemetry at 50 Hz
The simulator uses identical message definitions for its behavioural controller,
so recorded HIL logs can be replayed against simulated runs.
"""


def pin_number(pin: str) -> str:
    """Map a board pin id to an Arduino pin expression."""
    m = re.fullmatch(r"(?:GPIO|GP|D)(\d+)", pin)
    if m:
        return m.group(1)
    if re.fullmatch(r"A\d+", pin) or re.fullmatch(r"P[A-K]\d+", pin):
        return pin
    if pin.isdigit():
        return pin
    return pin


def _motor_constants(project: Project) -> tuple[float, float]:
    """Back-EMF constant at the wheel and nominal bus voltage, from the bound motor and battery."""
    from ...library.registry import REGISTRY  # noqa: PLC0415
    from ..power.models import DCMotor  # noqa: PLC0415
    from ..twin import resolve_twin  # noqa: PLC0415
    try:
        bindings, _, _ = resolve_twin(project, REGISTRY)
        b = next(x for x in bindings if x.motor is not None)
        ke = DCMotor.from_component(b.motor).ke * project.robot.drivetrain.gear_ratio
        return ke, b.bus_voltage_nominal or DCMotor.from_component(b.motor).v_rated
    except (StopIteration, ValueError):
        return 0.6, 12.0


def _channels(project: Project) -> dict:
    ch = {a.channel: pin_number(a.pin) for a in project.firmware.pin_map}
    return ch


def generate_main(project: Project) -> str:
    fw = project.firmware
    t = TARGETS.get(fw.target)
    ch = _channels(project)
    d = project.robot.drivetrain
    enc_cpr = 3200
    for a in project.robot.sensors:
        if a.type == "encoder" and a.params.get("cpr"):
            enc_cpr = int(a.params["cpr"])
    missing = [c for c in ("left_wheel_pwm", "right_wheel_pwm") if c not in ch]
    header = "\n".join(f"// WARNING: channel '{c}' not mapped; define it in the Firmware pin map" for c in missing)

    def P(name, default="-1"):
        return ch.get(name, default)

    isr_attr = "IRAM_ATTR " if fw.target == "esp32" else ""
    ke_wheel, vbus = _motor_constants(project)
    pwm_setup = """
#if defined(ESP32)
  #if ESP_ARDUINO_VERSION_MAJOR >= 3
    ledcAttach(PIN_L_PWM, 20000, 8); ledcAttach(PIN_R_PWM, 20000, 8);
  #else
    ledcSetup(0, 20000, 8); ledcAttachPin(PIN_L_PWM, 0); ledcSetup(1, 20000, 8); ledcAttachPin(PIN_R_PWM, 1);
  #endif
#else
  pinMode(PIN_L_PWM, OUTPUT); pinMode(PIN_R_PWM, OUTPUT);
#endif"""
    pwm_write = """
static void pwmWrite(int which, int pin, int duty) {
#if defined(ESP32)
  #if ESP_ARDUINO_VERSION_MAJOR >= 3
  (void)which; ledcWrite(pin, duty);
  #else
  (void)pin; ledcWrite(which, duty);
  #endif
#else
  (void)which; analogWrite(pin, duty);
#endif
}"""
    return f"""// Generated by RoboVerse Studio for "{project.name}" — target: {t.name if t else fw.target}
// Controller identical to the simulator's behavioural model: diff-drive kinematics + PI per wheel.
// Pins come from the project's firmware pin map. Re-generate after changing wiring.
{header}
#include <Arduino.h>

#define PIN_L_PWM {P('left_wheel_pwm')}
#define PIN_L_DIR_A {P('left_wheel_dir_a')}
#define PIN_L_DIR_B {P('left_wheel_dir_b')}
#define PIN_R_PWM {P('right_wheel_pwm')}
#define PIN_R_DIR_A {P('right_wheel_dir_a')}
#define PIN_R_DIR_B {P('right_wheel_dir_b')}
#define PIN_L_ENC_A {P('left_wheel_enc_a')}
#define PIN_L_ENC_B {P('left_wheel_enc_b')}
#define PIN_R_ENC_A {P('right_wheel_enc_a')}
#define PIN_R_ENC_B {P('right_wheel_enc_b')}

static const float WHEEL_RADIUS = {d.wheel_radius:.5f}f;   // m
static const float WHEEL_SEP = {d.wheel_separation:.5f}f;  // m
static const float MAX_V = {d.max_speed:.3f}f, MAX_ACC = {d.max_accel:.3f}f, MAX_DEC = {d.max_decel:.3f}f;
// Decoding uses CHANGE interrupts on channel A only (2x): half of the 4x counts-per-rev rating.
static const float ENC_CPR = {enc_cpr / 2:.1f}f;
static const float KP = {fw.controller.kp:.4f}f, KI = {fw.controller.ki:.4f}f, FF = {fw.controller.feedforward:.4f}f;
static const float LOOP_HZ = {fw.controller.loop_hz:.1f}f;
static const float KE_WHEEL = {ke_wheel:.5f}f;  // V per rad/s at the wheel, from the motor model (calibrate on hardware)
static const float VBUS = {vbus:.2f}f;       // nominal bus voltage

volatile long encL = 0, encR = 0;
float vRef = 0, wRef = 0, vCmd = 0, wCmd = 0, iL = 0, iR = 0, wL = 0, wR = 0;
long prevL = 0, prevR = 0;
bool estop = false;
unsigned long lastLoop = 0, lastTelem = 0, lastCmd = 0;

void {isr_attr}isrLeft() {{ encL += (digitalRead(PIN_L_ENC_B) == digitalRead(PIN_L_ENC_A)) ? 1 : -1; }}
void {isr_attr}isrRight() {{ encR += (digitalRead(PIN_R_ENC_B) == digitalRead(PIN_R_ENC_A)) ? -1 : 1; }}
{pwm_write}

static void drive(int which, int pwmPin, int dirA, int dirB, float duty) {{
  duty = constrain(duty, -1.0f, 1.0f);
  if (dirA >= 0) digitalWrite(dirA, duty >= 0 ? HIGH : LOW);
  if (dirB >= 0) digitalWrite(dirB, duty >= 0 ? LOW : HIGH);
  pwmWrite(which, pwmPin, (int)(fabs(duty) * 255.0f));
}}

static float wheelPI(float target, float meas, float &integ, float dt) {{
  float err = target - meas;
  float u = FF * target * KE_WHEEL / VBUS + (KP * err + integ) * KE_WHEEL / VBUS;
  if (fabs(u) < 1.0f || (u > 0) != (err > 0)) integ += KI * err * dt;  // conditional integration
  return constrain(u, -1.0f, 1.0f);
}}

static void readSerial() {{
  static char buf[64]; static uint8_t n = 0;
  while (Serial.available()) {{
    char c = Serial.read();
    if (c == '\\n' || n >= sizeof(buf) - 1) {{
      buf[n] = 0; n = 0;
      if (buf[0] == 'C') {{ char *p = buf + 1; vCmd = strtod(p, &p); wCmd = strtod(p, &p); lastCmd = millis(); }}
      else if (buf[0] == 'E') {{ estop = atoi(buf + 1) != 0; }}
    }} else buf[n++] = c;
  }}
}}

void setup() {{
  Serial.begin(115200);
{pwm_setup}
  if (PIN_L_DIR_A >= 0) pinMode(PIN_L_DIR_A, OUTPUT);
  if (PIN_L_DIR_B >= 0) pinMode(PIN_L_DIR_B, OUTPUT);
  if (PIN_R_DIR_A >= 0) pinMode(PIN_R_DIR_A, OUTPUT);
  if (PIN_R_DIR_B >= 0) pinMode(PIN_R_DIR_B, OUTPUT);
  if (PIN_L_ENC_A >= 0) {{ pinMode(PIN_L_ENC_A, INPUT_PULLUP); pinMode(PIN_L_ENC_B, INPUT_PULLUP);
    attachInterrupt(digitalPinToInterrupt(PIN_L_ENC_A), isrLeft, CHANGE); }}
  if (PIN_R_ENC_A >= 0) {{ pinMode(PIN_R_ENC_A, INPUT_PULLUP); pinMode(PIN_R_ENC_B, INPUT_PULLUP);
    attachInterrupt(digitalPinToInterrupt(PIN_R_ENC_A), isrRight, CHANGE); }}
}}

void loop() {{
  readSerial();
  if (millis() - lastCmd > 500) {{ vCmd = 0; wCmd = 0; }}  // command watchdog
  unsigned long now = micros();
  float dt = (now - lastLoop) * 1e-6f;
  if (dt < 1.0f / LOOP_HZ) return;
  lastLoop = now;
  float vt = estop ? 0 : constrain(vCmd, -MAX_V, MAX_V);
  float lim = (fabs(vt) > fabs(vRef) ? MAX_ACC : MAX_DEC) * dt;
  vRef += constrain(vt - vRef, -lim, lim);
  wRef = estop ? 0 : wCmd;
  noInterrupts(); long l = encL, r = encR; interrupts();
  wL = 0.7f * wL + 0.3f * ((l - prevL) / ENC_CPR * TWO_PI / dt);
  wR = 0.7f * wR + 0.3f * ((r - prevR) / ENC_CPR * TWO_PI / dt);
  prevL = l; prevR = r;
  float tl = (vRef - wRef * WHEEL_SEP / 2) / WHEEL_RADIUS, tr = (vRef + wRef * WHEEL_SEP / 2) / WHEEL_RADIUS;
  float dl = estop ? 0 : wheelPI(tl, wL, iL, dt), dr = estop ? 0 : wheelPI(tr, wR, iR, dt);
  if (estop) {{ iL = iR = 0; }}
  drive(0, PIN_L_PWM, PIN_L_DIR_A, PIN_L_DIR_B, dl);
  drive(1, PIN_R_PWM, PIN_R_DIR_A, PIN_R_DIR_B, dr);
  if (millis() - lastTelem >= 20) {{
    lastTelem = millis();
    Serial.print("T "); Serial.print(lastTelem); Serial.print(' '); Serial.print(l); Serial.print(' ');
    Serial.print(r); Serial.print(' '); Serial.print(dl, 3); Serial.print(' '); Serial.println(dr, 3);
  }}
}}
"""


def generate_platformio_project(project: Project) -> dict[str, str]:
    fw = project.firmware
    t = TARGETS.get(fw.target)
    files: dict[str, str] = {}
    if t and t.platformio_env:
        env = t.platformio_env
        files["platformio.ini"] = (f"; generated by RoboVerse Studio\n[env:{t.id}]\nplatform = {env['platform']}\n"
                                   f"board = {env['board']}\nframework = {env['framework']}\nmonitor_speed = 115200\n")
        files["src/main.cpp"] = generate_main(project)
    for f in fw.files:  # user sources override generated ones
        files[f.path] = f.content
    files["HIL_PROTOCOL.txt"] = HIL_PROTOCOL
    return files


def pio_path() -> str | None:
    return shutil.which("pio") or shutil.which("platformio")


ERR_RE = re.compile(r"^(?P<file>[^:\n]+):(?P<line>\d+):(?:(?P<col>\d+):)?\s*(?P<kind>error|warning|fatal error):\s*(?P<msg>.*)$")


def parse_compiler_output(text: str) -> list[dict]:
    out = []
    for line in text.splitlines():
        m = ERR_RE.match(line.strip())
        if m:
            out.append({"file": m["file"], "line": int(m["line"]), "column": int(m["col"]) if m["col"] else None,
                        "severity": "error" if "error" in m["kind"] else "warning", "message": m["msg"]})
    return out


def build_firmware(project: Project, timeout: float = 600.0) -> dict:
    exe = pio_path()
    files = generate_platformio_project(project)
    if not exe:
        return {"status": "unavailable", "toolchain": "platformio",
                "message": "PlatformIO CLI not found. Install with `pip install platformio`; the first build downloads the "
                           "target toolchain. Generated sources are still available for download.",
                "files": sorted(files), "diagnostics": []}
    if "platformio.ini" not in files:
        return {"status": "not_applicable", "message": "This target has no MCU firmware build (e.g. Linux SBC).", "diagnostics": []}
    with tempfile.TemporaryDirectory() as td:
        for path, content in files.items():
            p = Path(td) / path
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content)
        try:
            proc = subprocess.run([exe, "run", "-d", td], capture_output=True, text=True, timeout=timeout)
        except subprocess.TimeoutExpired:
            return {"status": "error", "message": "build timed out", "diagnostics": []}
        log = proc.stdout + proc.stderr
        artifacts = {}
        for fn in Path(td).glob(".pio/build/*/firmware.*"):
            import base64  # noqa: PLC0415
            artifacts[fn.name] = base64.b64encode(fn.read_bytes()).decode()
        return {"status": "success" if proc.returncode == 0 else "failed", "diagnostics": parse_compiler_output(log),
                "log": log[-8000:], "artifacts": artifacts,
                "note": "A successful build does not prove correct execution; validate in HIL or on hardware."}
