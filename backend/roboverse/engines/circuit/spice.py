def _fmt(v: float) -> str:
    return f"{v:.6g}"


def to_spice(circuit: Circuit, registry: Registry, title: str = "RoboVerse circuit", analysis: str = "op",
             t_stop: float = 1e-3, dt: float = 1e-5) -> tuple[str, list[dict]]:
    """Return (netlist text, skipped components). Unsupported parts are emitted as comments, never dropped silently."""
    prep = prepare(circuit, registry)
    nn = prep.node_names
    lines = [f"* {title}", f"* generated by RoboVerse Studio {datetime.now(timezone.utc).isoformat(timespec='seconds')}"]
    models = {}
    for e in prep.elements:
        a, b = nn[e.n1], nn[e.n2]
        if e.kind == "R":
            lines.append(f"R{e.name} {a} {b} {_fmt(e.value)}")
        elif e.kind == "C":
            lines.append(f"C{e.name} {a} {b} {_fmt(e.value)} IC=0")
        elif e.kind == "L":
            lines.append(f"L{e.name} {a} {b} {_fmt(e.value)}")
        elif e.kind == "V":
            if "pulse" in e.params:
                p = e.params["pulse"]
                lines.append(f"V{e.name} {a} {b} PULSE({_fmt(p['v1'])} {_fmt(p['v2'])} 0 1n 1n "
                             f"{_fmt(p['duty'] * p['period'])} {_fmt(p['period'])})")
            else:
                lines.append(f"V{e.name} {a} {b} DC {_fmt(e.value)}")
        elif e.kind == "I":
            lines.append(f"I{e.name} {a} {b} DC {_fmt(e.value)}")
        elif e.kind == "D":
            mname = f"D_{e.instance}"
            models[mname] = f".model {mname} D(IS={_fmt(e.params['is'])} N={_fmt(e.params['n'])})"
            lines.append(f"D{e.name} {a} {b} {mname}")
    for s in prep.skipped:
        lines.append(f"* NOT EXPORTED: {s['instance']} ({s['component']}) — {s['reason']}")
    lines += list(models.values())
    lines.append(".op" if analysis == "op" else f".tran {_fmt(dt)} {_fmt(t_stop)} UIC")
    lines.append(".end")
    return "\n".join(lines) + "\n", prep.skipped


def ngspice_path() -> Optional[str]:
    return shutil.which("ngspice")


def parse_ascii_raw(text: str) -> dict:
    """Parse an ngspice ASCII rawfile (single plot)."""
    lines = text.splitlines()
    variables: list[str] = []
    npoints = 0
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("No. Points:"):
            npoints = int(ln.split(":")[1])
        if ln.startswith("Variables:"):
            i += 1
            while i < len(lines) and not lines[i].startswith("Values:"):
                parts = lines[i].split()
                if len(parts) >= 2:
                    variables.append(parts[1])
                i += 1
            break
        i += 1
    data = {v: [] for v in variables}
    i += 1
    vals: list[float] = []
    while i < len(lines):
        parts = lines[i].split()
        if parts:
            # first value of each point is prefixed by the point index
            if len(parts) == 2 and len(vals) % len(variables) == 0:
                vals.append(float(parts[1].split(",")[0]))
            else:
                vals.append(float(parts[-1].split(",")[0]))
        i += 1
    for k in range(npoints):
        for j, v in enumerate(variables):
            idx = k * len(variables) + j
            if idx < len(vals):
                data[v].append(vals[idx])
    return data


def run_ngspice(netlist: str, timeout: float = 30.0) -> dict:
    exe = ngspice_path()
    if not exe:
        return {"engine": "ngspice", "status": "unavailable",
                "errors": ["ngspice is not installed. Install it (e.g. `apt install ngspice`) to enable this backend."]}
    with tempfile.TemporaryDirectory() as td:
        cir = Path(td) / "circuit.cir"
        raw = Path(td) / "out.raw"
        body = netlist.replace(".end\n", "")
        analysis = next((ln for ln in body.splitlines() if ln.startswith((".op", ".tran"))), ".op")
        body = "\n".join(ln for ln in body.splitlines() if not ln.startswith((".op", ".tran")))
        cir.write_text(body + f"\n.control\nset filetype=ascii\n{analysis[1:]}\nwrite {raw} all\n.endc\n.end\n")
        try:
            proc = subprocess.run([exe, "-b", str(cir)], capture_output=True, text=True, timeout=timeout)
        except subprocess.TimeoutExpired:
            return {"engine": "ngspice", "status": "error", "errors": ["ngspice timed out"]}
        if not raw.exists():
            return {"engine": "ngspice", "status": "error", "errors": [proc.stderr[-2000:] or proc.stdout[-2000:]]}
        return {"engine": "ngspice", "status": "ok", "result_kind": "circuit_solver",
                "data": parse_ascii_raw(raw.read_text()), "log": proc.stdout[-4000:]}


def to_kicad_netlist(circuit: Circuit, registry: Registry, source: str = "roboverse") -> str:
    """KiCad netlist (s-expression, format 'E') importable by Pcbnew for footprint placement/routing."""
    g = build_nets(circuit, registry)

    def q(s: str) -> str:
        return '"' + str(s).replace('"', "'") + '"'

    out = ["(export (version \"E\")",
           f"  (design (source {q(source)}) (date {q(datetime.now(timezone.utc).isoformat(timespec='seconds'))}) "
           "(tool \"RoboVerse Studio\"))", "  (components"]
    for inst in circuit.instances:
        comp = g.components.get(inst.id)
        if not comp:
            continue
        value = inst.params.get("resistance") or inst.params.get("capacitance") or comp.part_number or comp.name
        fp = f" (footprint {q(comp.footprint)})" if comp.footprint else ""
        ds = f" (datasheet {q(comp.datasheet)})" if comp.datasheet else ""
        out.append(f"    (comp (ref {q(inst.id)}) (value {q(value)}){fp}{ds} "
                   f"(libsource (lib \"roboverse\") (part {q(comp.id)}) (description {q(comp.name)})))")
    out.append("  )")
    out.append("  (nets")
    code = 1
    for n in g.nets:
        if len(n.pins) < 2:
            continue
        nodes = " ".join(f"(node (ref {q(p.instance.id)}) (pin {q(p.pin.id)}) (pinfunction {q(p.pin.name)}))" for p in n.pins)
        out.append(f"    (net (code {q(code)}) (name {q(n.name or n.id)}) {nodes})")
        code += 1
    out.append("  )")
    out.append(")")
    return "\n".join(out) + "\n"
